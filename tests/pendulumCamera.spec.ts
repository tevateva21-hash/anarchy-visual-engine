import { test, expect } from '@playwright/test';
import { createHash } from 'node:crypto';
import { wav } from './wav';
const hash = (bytes: Buffer) => createHash('sha256').update(bytes).digest('hex');

test('Pendulum Push seeks repeatably from wide to close-up, restores the previous view and preserves audio', async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/'); await page.locator('.therapy-viewport[data-ready=true]').waitFor();
  const canvas = page.getByRole('img', { name: /Techno Therapy Room : salle/ });
  const capture = async () => {
    await canvas.evaluate(element => element.scrollIntoView({ block: 'center', inline: 'nearest' }));
    return canvas.screenshot();
  };
  await page.getByLabel('Importer un MP3 ou WAV').setInputFiles({ name: 'camera.wav', mimeType: 'audio/wav', buffer: wav(3, 1000) });
  await expect(page.getByRole('status')).toContainText('Analyse prête');
  const audioSource = await page.locator('audio').getAttribute('src');
  await page.getByLabel(/Position d’analyse/).fill('1');
  await page.getByLabel('Point de vue').selectOption('divan');
  await page.getByLabel('Instant de la pièce').fill('3');
  const original = hash(await capture());
  const timeline = page.getByLabel('Timeline Pendulum Push');
  await expect(page.getByLabel('Durée du travelling')).toHaveValue('8');
  await timeline.fill('0'); const wide = await capture();
  await timeline.fill('8'); const close = await capture();
  expect(hash(close)).not.toBe(hash(wide));
  await timeline.fill('4'); const middle = hash(await capture());
  await timeline.fill('8'); await capture();
  await timeline.fill('4'); expect(hash(await capture())).toBe(middle);
  await page.getByLabel('Durée du travelling').fill('16');
  await expect(timeline).toHaveValue('8'); await expect(timeline).toHaveAttribute('max', '16');
  await timeline.fill('16'); await capture();
  await page.getByRole('button', { name: 'Revenir à la caméra initiale' }).click();
  await expect(page.getByLabel('Point de vue')).toHaveValue('divan');
  await expect(page.getByLabel('Instant de la pièce')).toHaveValue('3');
  expect(hash(await capture())).toBe(original);
  await expect(page.locator('audio')).toHaveAttribute('src', audioSource!);
  expect(await page.locator('audio').evaluate((a: HTMLAudioElement) => a.paused)).toBe(true);
  await expect(page.getByRole('img', { name: /Waveform/ })).toBeVisible();
  await expect(page.getByTestId('RMS')).toHaveText(/0\.35/);
  await testInfo.attach('Plan large', { body: wide, contentType: 'image/png' });
  await testInfo.attach('Gros plan', { body: close, contentType: 'image/png' });
  expect(errors).toEqual([]);
});

test('Play Pause Replay and finite duration use absolute time without triggering audio; reduced motion stops playback', async ({ page }) => {
  await page.goto('/'); await page.locator('.therapy-viewport[data-ready=true]').waitFor();
  await page.clock.install();
  const timeline = page.getByLabel('Timeline Pendulum Push');
  const play = page.getByRole('button', { name: 'Play Pendulum Push', exact: true });
  const pause = page.getByRole('button', { name: 'Pause Pendulum Push', exact: true });
  const replay = page.getByRole('button', { name: 'Replay Pendulum Push', exact: true });
  await timeline.fill('1.01');
  await play.click(); await page.clock.runFor(200);
  expect(Number(await timeline.inputValue())).toBeGreaterThan(1.01);
  await pause.click(); const stopped = await timeline.inputValue();
  await page.clock.runFor(500); await expect(timeline).toHaveValue(stopped);
  await play.click(); await page.clock.runFor(100);
  expect(Number(await timeline.inputValue())).toBeGreaterThan(Number(stopped));
  await replay.click(); await page.clock.runFor(100);
  expect(Number(await timeline.inputValue())).toBeLessThan(0.2);
  await page.clock.fastForward(9000); await expect(timeline).toHaveValue('8');
  await expect(pause).toBeDisabled(); await expect(play).toBeEnabled();
  await replay.click(); await page.clock.runFor(100);
  expect(Number(await timeline.inputValue())).toBeLessThan(0.2);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  // Media-query change is dispatched on a rendering cycle; advance the installed fake clock.
  await page.clock.runFor(100);
  await expect(play).toBeDisabled(); await expect(replay).toBeDisabled();
  await expect(pause).toBeDisabled(); const reducedTime = await timeline.inputValue();
  await page.clock.runFor(500); await expect(timeline).toHaveValue(reducedTime);
  await timeline.fill('4'); await expect(timeline).toHaveValue('4');
});
